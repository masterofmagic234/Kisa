// Render the real player in resumable segments; mix the untouched voice once.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {spawn}=require('node:child_process'),{once}=require('node:events');
const {chromium}=require('playwright');
(async()=>{
  const [html,voice,road,subtitles,destination,fpsArg]=process.argv.slice(2),fps=Number(fpsArg||24);
  const source=fs.readFileSync(html,'utf8');
  const jpegQuality=.88,width=1280,height=720;
  const encodeArgs=['-an','-c:v','libx264','-preset','fast','-crf','21','-threads','1','-pix_fmt','yuv420p','-movflags','+faststart'];
  const policy=JSON.stringify({version:1,fps,width,height,jpegQuality,encodeArgs});
  const digest=crypto.createHash('sha256').update(source).update(policy).digest('hex');
  const cache=destination+'.render-chunks/'+digest.slice(0,16);fs.mkdirSync(cache,{recursive:true});
  const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const pages=await Promise.all([0,1].map(async()=>{
    const page=await browser.newPage({viewport:{width,height}});page.errors=[];
    page.on('pageerror',e=>page.errors.push(e.message));
    await page.setContent(source,{waitUntil:'load'});await page.evaluate(()=>document.fonts.ready);
    await page.waitForFunction(()=>!document.querySelector('#start').disabled);return page;
  }));
  const duration=await pages[0].evaluate(()=>window.INTRO.book.duration),total=duration+3,frames=Math.ceil(total*fps);
  const perChunk=30*fps,count=Math.ceil(frames/perChunk);let cursor=0,finished=0;
  async function processChunk(page,index){
    const first=index*perChunk,last=Math.min(frames,first+perChunk);
    const target=path.join(cache,`chunk-${String(index).padStart(3,'0')}.mp4`),marker=target+'.ok.json';
    if(fs.existsSync(target)&&fs.existsSync(marker)){
      try{
        const record=JSON.parse(fs.readFileSync(marker,'utf8'));
        if(record.frames===last-first&&record.bytes===fs.statSync(target).size){console.log(`REUSED ${index+1}/${count}`);return;}
      }catch{} // An interrupted marker write is a cache miss, not a failed job.
    }
    const partial=target+'.partial.mp4';
    const encoder=spawn('ffmpeg',['-hide_banner','-loglevel','error','-y','-f','image2pipe','-vcodec','mjpeg','-framerate',String(fps),'-i','pipe:0',...encodeArgs,partial],{stdio:['pipe','ignore','pipe']});
    let stderr='';encoder.stderr.on('data',x=>stderr=(stderr+x).slice(-10000));encoder.stdin.on('error',()=>{});
    const completed=once(encoder,'close');
    try{
      for(let n=first;n<last;n++){
        const frame=await page.evaluate(({t,q})=>{window.INTRO.renderMovieFrame(t);return document.querySelector('canvas').toDataURL('image/jpeg',q)},{t:n/fps,q:jpegQuality});
        if(!encoder.stdin.write(Buffer.from(frame.split(',')[1],'base64')))await once(encoder.stdin,'drain');
      }
      encoder.stdin.end();const [code]=await completed;if(code!==0)throw new Error(stderr||'Segment encoder failed');
      if(page.errors.length)throw new Error(page.errors.join('\n'));
      fs.renameSync(partial,target);fs.writeFileSync(marker,JSON.stringify({frames:last-first,bytes:fs.statSync(target).size}));
    }catch(e){encoder.stdin.destroy();encoder.kill();throw e;}
    console.log(`RENDERED ${++finished}/${count} segments; ${Math.min(total,last/fps).toFixed(1)}s endpoint`);
  }
  try{await Promise.all(pages.map(async page=>{while(cursor<count){const index=cursor++;await processChunk(page,index);}}));}
  finally{await browser.close();}
  const concat=path.join(cache,'segments.txt');
  // Cache paths are generated by this exporter, not user-provided list entries.
  fs.writeFileSync(concat,Array.from({length:count},(_,i)=>`file '${path.resolve(cache,`chunk-${String(i).padStart(3,'0')}.mp4`).replaceAll("'","'\\''")}'`).join('\n')+'\n');
  const filter=`[1:a]apad=pad_dur=3[voice];[2:a]volume=0.045,afade=t=out:st=${duration-.5}:d=0.5[road];[voice][road]amix=inputs=2:duration=first:normalize=0,alimiter=limit=0.95[a]`;
  const finalPartial=destination+'.partial.mp4';
  const encoder=spawn('ffmpeg',['-hide_banner','-loglevel','error','-y','-f','concat','-safe','0','-i',concat,'-i',voice,'-stream_loop','-1','-i',road,'-filter_complex',filter,'-map','0:v','-map','[a]','-t',String(total),'-c:v','copy','-c:a','aac','-b:a','128k','-ar','48000','-ac','2','-movflags','+faststart',finalPartial],{stdio:['ignore','ignore','pipe']});
  let stderr='';encoder.stderr.on('data',x=>stderr=(stderr+x).slice(-10000));const [code]=await once(encoder,'close');
  if(code!==0)throw new Error(stderr||'Final mux failed');
  fs.renameSync(finalPartial,destination);
  console.log(JSON.stringify({status:'PASS',duration:total,fps,frames,segments:count,source:'same visual storyboard as game',subtitle_sidecar:true,destination}));
})().catch(e=>{console.error(e);process.exit(1)});
